/** Polska odmiana liczebników: 1 zadanie, 2 zadania, 5 zadań (12–14 jak 5). */
export function plural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one
  const d = n % 10
  const dd = n % 100
  return d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? few : many
}

